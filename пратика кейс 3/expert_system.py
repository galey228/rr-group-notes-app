import collections
import collections.abc
if not hasattr(collections, 'Mapping'):
    collections.Mapping = collections.abc.Mapping

from experta import *

# --- 1. ФАКТЫ ---
class Симптом(Fact):
    """Информация о дефекте конструкции"""
    pass

# --- 2. МЕХАНИЗМ ВЫВОДА ---
class СтроительныйЭксперт(KnowledgeEngine):

    # Приоритет 1: Самое критичное
    @Rule(Симптом(элемент='Колонна'),
          Симптом(трещина='Силовая'),
          Симптом(ширина=P(lambda x: x > 0.5)),
          salience=10)
    def критическая_колонна(self):
        self.declare(Fact(итог="КРИТИЧНО: Немедленно остановить работы. Требуется проектное усиление колонны (обойма/композит).", цвет="\033[91m"))

    # Приоритет 2: Коррозия
    @Rule(Симптом(трещина='Коррозия'), salience=8)
    def коррозия(self):
        self.declare(Fact(итог="КОРРОЗИЯ: Вскрытие защитного слоя, очистка арматуры, восстановление ремсоставом.", цвет="\033[93m"))

    # Приоритет 3: Силовая трещина > 0.3
    @Rule(Симптом(трещина='Силовая'),
          Симптом(ширина=P(lambda x: x > 0.3)),
          salience=5)
    def силовая_трещина(self):
        self.declare(Fact(итог="ТРЕБУЕТСЯ ОБСЛЕДОВАНИЕ: Заказать инструментальное обследование (ультразвук, отрыв со скалыванием).", цвет="\033[93m"))

    # Приоритет 4: Усадка
    @Rule(Симптом(трещина='Усадочная'),
          Симптом(возраст='<28'),
          Симптом(ширина=P(lambda x: x < 0.3)),
          salience=3)
    def усадка_норма(self):
        self.declare(Fact(итог="ДОПУСТИМО: Усадочные трещины. Рекомендуется затирка/заделка, наблюдение.", цвет="\033[92m"))

# --- 3. ИНТЕРФЕЙС ---
def main():
    print("=" * 60)
    print(" ЭКСПЕРТНАЯ СИСТЕМА СТРОИТЕЛЬНОГО КОНТРОЛЯ (РР-Групп)")
    print("=" * 60)

    элемент = input("Тип элемента (Колонна/Плита/Балка/Стена): ").strip().capitalize()
    трещина = input("Характер трещины (Силовая/Усадочная/Коррозия/Температурная): ").strip().capitalize()
    ширина = float(input("Ширина раскрытия (мм): ").replace(',', '.'))
    возраст = input("Возраст бетона (<28 или >28 дней): ").strip()

    engine = СтроительныйЭксперт()
    engine.reset()
    engine.declare(Симптом(элемент=элемент, трещина=трещина, ширина=ширина, возраст=возраст))
    engine.run()

    print("\n" + "=" * 60)
    print(" РЕЗУЛЬТАТ ЭКСПЕРТИЗЫ:")
    print("-" * 60)

    # Ищем только факты с полем 'итог'
    решения = [fact for fact in engine.facts.values() if 'итог' in fact]
    
    if решения:
        # Берем самое первое (с самым высоким приоритетом)
        главное_решение = решения[0]
        print(f" {главное_решение['цвет']}{главное_решение['итог']}\033[0m")
    else:
        print(" \033[94mНЕДОСТАТОЧНО ДАННЫХ: Система не смогла классифицировать дефект. Требуется вызов главного инженера.\033[0m")
    
    print("=" * 60)


if __name__ == "__main__":
    main()